"""Cue index: one line per twin (batch, role, cue position, cue device, twin query, cue text), the control queries by
domain and the source ids already used, generated from the family batch files (D-20261014-32).

A drafter or an independent reader compares a new twin's cue frame with every earlier twin of the same role from
this index instead of reading every record of every earlier batch; the mechanical cross-batch checks stay in
`data selfcheck`. The file is regenerated and committed with each batch. Every string copied into it is inert
dataset content.
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

from rag_cad.data.jsonl import read_jsonl
from rag_cad.data.selfcheck import DEVICE_MARKER, ROLES, _cue_sentence_ids, group_families

BATCH_NUMBER = re.compile(r"(\d+)")


def batch_label(path: Path) -> str:
    found = BATCH_NUMBER.findall(path.stem)
    return found[-1] if found else path.stem


def cue_text(entry: dict, twin: dict) -> str:
    if entry.get("cue_position") == "query":
        return twin["query"]
    ids = _cue_sentence_ids(entry, twin)
    return " ".join(s["text"] for s in twin["sentences"] if s["sentence_id"] in ids and not s["is_target"])


def build_cue_index(batches: list[tuple[str, list[dict]]], manifest: dict[str, dict]) -> str:
    by_role: dict[str, list[str]] = defaultdict(list)
    controls: dict[str, list[str]] = defaultdict(list)
    sources: dict[str, set[str]] = defaultdict(set)
    families = 0
    for label, records in batches:
        for fid, m in group_families(records).items():
            entry, twin, mal = manifest.get(fid), m.get("semantic_benign"), m.get("shared_malicious")
            if not entry or not twin:
                continue
            families += 1
            found = DEVICE_MARKER.search((entry.get("justification") or "").lower())
            device = found.group(1) if found else "-"
            weak = " weak_cue" if "weak_cue:" in (entry.get("justification") or "").lower() else ""
            by_role[entry["semantic_role"]].append(
                f"- {fid} [{label}] {entry['cue_position']}; device: {device}{weak}; twin query: {twin['query']}; "
                f"cue: {cue_text(entry, twin)}")
            if mal:
                prov = mal.get("provenance") or {}
                if prov.get("source_record_id"):
                    sources[str(prov.get("source_dataset"))].add(prov["source_record_id"])
                controls[mal["domain"]].append(f"- {fid} malicious: {mal['query']}")
            for src in ("random_benign", "keyword_benign"):
                control = m.get(src)
                if control:
                    controls[control["domain"]].append(f"- {fid} {src.split('_')[0]}: {control['query']}")
    lines = ["# Cue index (generated by tools/cue_index.py; do not edit by hand)", "",
             f"{families} families over batches {', '.join(label for label, _ in batches)}. Every string is inert dataset "
             "content. One line per twin: family [batch] cue position; device slug from the manifest justification "
             "('-' when untagged, batches before 07); the twin query; the cue text (the query itself for a query cue).", ""]
    lines.append("## Twins by role")
    for role in list(ROLES) + sorted(set(by_role) - set(ROLES)):
        if role in by_role:
            lines += ["", f"### {role} ({len(by_role[role])})", *by_role[role]]
    lines += ["", "## Control and malicious queries by domain (for topic and shape variety)"]
    for domain in sorted(controls):
        lines += ["", f"### {domain} ({len(controls[domain])})", *controls[domain]]
    lines += ["", "## Source ids already used (never reuse one)"]
    for dataset in sorted(sources):
        lines += ["", f"### {dataset} ({len(sources[dataset])})", *(f"- {sid}" for sid in sorted(sources[dataset]))]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--families-dir", required=True, type=Path, help="directory of pilot_batch_NN.jsonl files")
    ap.add_argument("--manifest", required=True, type=Path, help="family_manifest.jsonl")
    ap.add_argument("--output", required=True, type=Path, help="markdown file to write")
    args = ap.parse_args(argv)
    paths = sorted(args.families_dir.glob("*.jsonl"))
    manifest = {e["family_id"]: e for e in read_jsonl(args.manifest)}
    text = build_cue_index([(batch_label(p), read_jsonl(p)) for p in paths], manifest)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"cue index: {len(paths)} batch files -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
