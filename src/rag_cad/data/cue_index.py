"""Cue index: one line per twin (batch, role, cue position, cue device, twin query, cue text), the control queries by
domain and the source ids already used, generated from the family batch files (D-20261014-32).

A drafter or an independent reader compares a new twin's cue frame with every earlier twin of the same role from
this index instead of reading every record of every earlier batch; the mechanical cross-batch checks stay in
`data selfcheck`. The file is regenerated and committed with each batch. Every string copied into it is inert
dataset content.

The compact device index (D-20261015-37) is the drafters' and finalisers' working copy: devices per role without
the cue texts, the first words of every query by domain, and the source ids used. The full index stays for the
reader and for the S12 comparison of one role (read that role's section only).
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

from rag_cad.data.jsonl import read_jsonl
from rag_cad.data.selfcheck import DEVICE_MARKER, ROLES, _cue_sentence_ids, group_families

BATCH_NUMBER = re.compile(r"(\d+)")
QUERY_WORDS = 6
RECENT_BATCHES = 3  # D-20261015-38: the compact index lists queries of the last three batches only


def batch_label(path: Path) -> str:
    found = BATCH_NUMBER.findall(path.stem)
    return found[-1] if found else path.stem


def cue_text(entry: dict, twin: dict) -> str:
    if entry.get("cue_position") == "query":
        return twin["query"]
    ids = _cue_sentence_ids(entry, twin)
    return " ".join(s["text"] for s in twin["sentences"] if s["sentence_id"] in ids and not s["is_target"])


def _collect(batches: list[tuple[str, list[dict]]], manifest: dict[str, dict]) -> dict:
    by_role: dict[str, list[dict]] = defaultdict(list)
    queries: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    sources: dict[str, set[str]] = defaultdict(set)
    families = 0
    for label, records in batches:
        for fid, m in group_families(records).items():
            entry, twin, mal = manifest.get(fid), m.get("semantic_benign"), m.get("shared_malicious")
            if not entry or not twin:
                continue
            families += 1
            found = DEVICE_MARKER.search((entry.get("justification") or "").lower())
            by_role[entry["semantic_role"]].append({
                "fid": fid, "label": label, "cue_position": entry["cue_position"],
                "device": found.group(1) if found else "-",
                "weak": "weak_cue:" in (entry.get("justification") or "").lower(),
                "query": twin["query"], "cue": cue_text(entry, twin)})
            if mal:
                prov = mal.get("provenance") or {}
                if prov.get("source_record_id"):
                    sources[str(prov.get("source_dataset"))].add(prov["source_record_id"])
                queries[mal["domain"]].append((fid, "malicious", mal["query"]))
            queries[twin["domain"]].append((fid, "twin", twin["query"]))
            for src in ("random_benign", "keyword_benign"):
                control = m.get(src)
                if control:
                    queries[control["domain"]].append((fid, src.split("_")[0], control["query"]))
    labels = [label for label, _ in batches]
    recent_families = {it["fid"] for items in by_role.values() for it in items if it["label"] in labels[-RECENT_BATCHES:]}
    return {"by_role": by_role, "queries": queries, "sources": sources, "families": families,
            "labels": labels, "recent_families": recent_families}


def _roles(by_role: dict) -> list[str]:
    return list(ROLES) + sorted(set(by_role) - set(ROLES))


def _sources_section(sources: dict[str, set[str]]) -> list[str]:
    lines = ["", "## Source ids already used (never reuse one)"]
    for dataset in sorted(sources):
        lines += ["", f"### {dataset} ({len(sources[dataset])})", *(f"- {sid}" for sid in sorted(sources[dataset]))]
    return lines


def build_cue_index(batches: list[tuple[str, list[dict]]], manifest: dict[str, dict]) -> str:
    data = _collect(batches, manifest)
    lines = ["# Cue index (generated by tools/cue_index.py; do not edit by hand)", "",
             f"{data['families']} families over batches {', '.join(data['labels'])}. Every string is inert dataset "
             "content. One line per twin: family [batch] cue position; device slug from the manifest justification "
             "('-' when untagged, batches before 07); the twin query; the cue text (the query itself for a query cue).", ""]
    lines.append("## Twins by role")
    for role in _roles(data["by_role"]):
        items = data["by_role"].get(role)
        if items:
            lines += ["", f"### {role} ({len(items)})"]
            for it in items:
                weak = " weak_cue" if it["weak"] else ""
                lines.append(f"- {it['fid']} [{it['label']}] {it['cue_position']}; device: {it['device']}{weak}; "
                             f"twin query: {it['query']}; cue: {it['cue']}")
    lines += ["", "## Control and malicious queries by domain (for topic and shape variety)"]
    for domain in sorted(data["queries"]):
        rows = data["queries"][domain]
        lines += ["", f"### {domain} ({len(rows)})", *(f"- {fid} {kind}: {query}" for fid, kind, query in rows if kind != "twin")]
    lines += _sources_section(data["sources"])
    return "\n".join(lines) + "\n"


def build_device_index(batches: list[tuple[str, list[dict]]], manifest: dict[str, dict]) -> str:
    data = _collect(batches, manifest)
    lines = ["# Device index (generated by tools/cue_index.py; do not edit by hand)", "",
             f"{data['families']} families over batches {', '.join(data['labels'])}. Compact working copy for drafters and "
             "finalisers (D-20261015-37): devices per role, the opening words of every query by domain, the source ids used. "
             "For the cue text of one role read that role's section of review/cue_index.md.", ""]
    lines.append("## Devices by role")
    for role in _roles(data["by_role"]):
        items = data["by_role"].get(role)
        if items:
            counts = defaultdict(int)
            for it in items:
                counts[it["device"]] += 1
            summary = ", ".join(f"{slug} {n}" for slug, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))
            lines += ["", f"### {role} ({len(items)}): {summary}"]
            lines += [f"- {it['fid']} [{it['label']}] {it['cue_position']}; {it['device']}{' weak_cue' if it['weak'] else ''}"
                      for it in items]
    recent = set(data["labels"][-RECENT_BATCHES:])
    lines += ["", f"## Query openings by domain, last {len(recent)} batches (first {QUERY_WORDS} words; malicious, twin, random, keyword). "
              "Exact and near reuse across all batches is checked mechanically; this list is for topic and shape variety."]
    for domain in sorted(data["queries"]):
        rows = [(fid, kind, query) for fid, kind, query in data["queries"][domain] if fid in data["recent_families"]]
        lines += ["", f"### {domain} ({len(rows)})"]
        lines += [f"- {fid} {kind}: {' '.join(query.split()[:QUERY_WORDS])}" for fid, kind, query in rows]
    lines += _sources_section(data["sources"])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--families-dir", required=True, type=Path, help="directory of pilot_batch_NN.jsonl files")
    ap.add_argument("--manifest", required=True, type=Path, help="family_manifest.jsonl")
    ap.add_argument("--output", required=True, type=Path, help="markdown file to write (the full cue index)")
    ap.add_argument("--compact-output", type=Path, help="markdown file for the compact device index")
    args = ap.parse_args(argv)
    paths = sorted(args.families_dir.glob("*.jsonl"))
    manifest = {e["family_id"]: e for e in read_jsonl(args.manifest)}
    batches = [(batch_label(p), read_jsonl(p)) for p in paths]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_cue_index(batches, manifest), encoding="utf-8", newline="\n")
    print(f"cue index: {len(paths)} batch files -> {args.output}")
    if args.compact_output:
        args.compact_output.parent.mkdir(parents=True, exist_ok=True)
        args.compact_output.write_text(build_device_index(batches, manifest), encoding="utf-8", newline="\n")
        print(f"device index -> {args.compact_output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
